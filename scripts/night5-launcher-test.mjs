import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {readFileSync,existsSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {night5ChildArgs} from './night5-child-args.mjs';
const source=resolve(fileURLToPath(new URL('..',import.meta.url)));
const [out,hitboxes]=process.argv.slice(2);
assert(out&&hitboxes&&!existsSync(out),'Provide new pilot output and hitboxes');
const argv=night5ChildArgs(source,'server/scripts/ttkSurvey.ts',['--trial=night5','--block=mountain','--mode=pilot',`--out=${out}`,`--hitboxes=${hitboxes}`]);
assert.equal(new URL(argv[1]).protocol,'file:');
assert.deepEqual(night5ChildArgs(source,'scripts/night5-audit.mjs',[out]),['scripts/night5-audit.mjs',out]);
const result=spawnSync(process.execPath,argv,{cwd:source,encoding:'utf8',windowsHide:true,timeout:120000});
assert.equal(result.error,undefined,String(result.error));
assert.equal(result.status,0,result.stderr+result.stdout);
const read=n=>JSON.parse(readFileSync(join(out,n),'utf8'));
assert.equal(read('manifest.json').mode,'pilot');
assert.equal(read('complete.json').runs,4);
assert(read('index.json').every(r=>r.outcome==='window-ended'));
const audit=spawnSync(process.execPath,night5ChildArgs(source,'scripts/night5-audit.mjs',[out]),{cwd:source,encoding:'utf8',windowsHide:true,timeout:30000});
assert.equal(audit.status,0,audit.stderr+audit.stdout);
assert.equal(read('night5-audit.json').rows.length,4);
console.log('Night5 exact child launch + four pilots + audit: passed');
