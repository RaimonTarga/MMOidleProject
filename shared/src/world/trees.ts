// ─── Scattered forest trees ───────────────────────────────────────────────────
//
// Trees are generated deterministically per node from the node id, so the server
// (movement blocking) and every client (rendering + collision overlay) agree on
// the exact same layout without any network traffic. The art lives in a 2×2
// sprite sheet (`trees.png`); each of the four cells is one tree variant.
//
// The trunk hitboxes below were baked from the matching `trees_hitbox.png` with
// the same greedy-rect-cover algorithm used for monster/player sprites, so the
// footprint hugs the actual trunk + roots instead of a loose circle. Regenerate
// with `pnpm --filter @mmo-idle/server bake:tree-hitboxes`.

/** Biome family that receives scattered trees. */
export const TREE_BIOME_GROUP = "forest";

/** Number of tree variants in the sheet (2×2 grid). */
export const TREE_VARIANT_COUNT = 4;

/** One tree cell is 1024×1024 within the 2048×2048 sheet. */
export const TREE_CELL_PX = 1024;

/** Base on-screen size (node px) of a tree cell before per-tree size jitter. */
export const TREE_DISPLAY_BASE = 480;

export type TreeArtSet =
  | "forest"
  | "jungle"
  | "plains"
  | "swamp"
  | "tundra"
  | "wasteland"
  | "cave-rock"
  | "desert-rock"
  | "volcanic-rock"
  | "trench-rock";

